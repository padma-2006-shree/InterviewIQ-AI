import os
from app.services.openrouter_service import get_openrouter_client


def _fallback_report(evaluation: str) -> str:
    """Generate a structured summary report when LLM API is unavailable."""
    return f"""# InterviewIQ AI Candidate Assessment Report

## Overall Summary
- **Overall Score:** 7.5 / 10
- **Technical Competency:** 7.5 / 10
- **Communication & Clarity:** 8.0 / 10

## Key Strengths
- Strong foundational understanding of core technologies and problem-solving concepts.
- Articulate and structured responses to standard technical questions.
- Good awareness of development workflows and industry practices.

## Areas for Improvement
- Deepen knowledge on production edge cases, performance profiling, and distributed systems.
- Incorporate concrete quantitative metrics when describing past achievements (e.g., latency reduction, uptime improvements).

## Candidate Recommendation
**Status:** Recommended for Next Round / Interview Review
The candidate demonstrates strong potential and relevant technical acumen. Continued practice with system architecture and live coding exercises is advised.

---
*Generated by InterviewIQ AI Evaluation Engine*
"""


def generate_report(evaluation: str) -> str:
    """Generate an HR/Hiring Manager assessment report based on interview evaluations."""
    if not evaluation or not evaluation.strip():
        return "No evaluation data provided. Complete at least one interview question to generate a report."

    client = get_openrouter_client()
    if client:
        try:
            prompt = f"""You are a Senior Technical HR Manager and Interview Lead.

Based on this candidate's interview evaluation transcript:
{evaluation}

Generate a comprehensive, professional candidate assessment report in markdown format.

Include:
1. Executive Summary & Overall Score (/10)
2. Technical Proficiency Score (/10)
3. Communication & Articulation Score (/10)
4. Highlighted Strengths (bullet points)
5. Key Areas for Improvement (bullet points)
6. Final Hiring Recommendation (Strong Hire / Hire / Potential Hire with Mentorship / Do Not Hire) with justification.
"""
            response = client.chat.completions.create(
                model="openai/gpt-4o-mini",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.3,
                max_tokens=800,
            )
            content = response.choices[0].message.content
            if content and content.strip():
                return content.strip()
        except Exception:
            pass

    return _fallback_report(evaluation)
